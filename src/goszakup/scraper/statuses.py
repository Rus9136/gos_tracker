def status_name(code: int | None) -> str | None:
    if code is None:
        return None
    return STATUS_NAMES.get(int(code))


def status_tone(code: int | None) -> str:
    if code is None:
        return "muted"
    return STATUS_TONES.get(int(code), "muted")


def is_actual(code: int | None) -> bool:
    if code is None:
        return False
    return int(code) in ACTUAL_STATUSES
