# Группы для удобной фильтрации в UI и preset'ах.
# ACTUAL = «приём ещё открыт, можно участвовать»: публикация, приём
# заявок/ценовых предложений, ожидание аукциона. Статусы рассмотрения и
# формирования протоколов (250/260/270/310/320/325/330) — приём УЖЕ закрыт,
# участвовать нельзя, поэтому они в SPECIAL (процессуальные), а не ACTUAL.
# Пресеты по-прежнему скрейпят все статусы (их status_codes заморожены в БД),
# меняется только пометка is_actual. См. правило #14.
ACTUAL_STATUSES: list[int] = [210, 220, 230, 240, 280]
PAST_STATUSES: list[int] = [360, 370, 410, 430]
SPECIAL_STATUSES: list[int] = [
    190, 250, 260, 270, 310, 320, 325, 330, 420, 440, 444, 445, 460, 510, 540, 550,
]

# Семантический «тон» статуса для UI — фоновая окраска пилюли (StatusPill).
# Маппинг зафиксирован в design_handoff README §«Statuses → tone mapping».
